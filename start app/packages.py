def validate_packages(value) -> list[str]:
    if (not isinstance(value, list)
            or any(not isinstance(item, str) or item not in _PACKAGE_IDS for item in value)):
        raise ValueError("Selected packages must be a list of known package IDs")
    unsupported = sorted(item for item in set(value) if item in _PACKAGE_SYSTEMS and SYSTEM not in _PACKAGE_SYSTEMS[item])
    if unsupported:
        raise ValueError(f"Packages unavailable on {SYSTEM or platform.machine()}: {', '.join(unsupported)}")
    return sorted(set(value))
